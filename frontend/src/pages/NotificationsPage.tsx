import { useState } from 'react';
import { ArrowRight, Bell, CheckCheck, CircleHelp, LockKeyhole, ReceiptText, Sparkles, Trash2 } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useDemo } from '../context/DemoProvider';
import { formatRelativeDate } from '../types';
import { Button } from '../components/Controls';
import { EmptyState } from '../components/EmptyState';
import { Modal } from '../components/Modal';
import { PageHeader } from '../components/PageHeader';

const iconForKind = (kind: string) => kind === 'security' ? LockKeyhole : kind === 'tip' ? Sparkles : kind === 'payment' ? ReceiptText : Bell;

export default function NotificationsPage() {
  const { notifications, markNotificationRead, markAllNotificationsRead, clearNotifications } = useDemo();
  const navigate = useNavigate();
  const [clearConfirmOpen, setClearConfirmOpen] = useState(false);
  const unreadCount = notifications.filter((item) => !item.read).length;

  const openNotification = (id: string, href: string) => {
    markNotificationRead(id);
    navigate(href);
  };

  const confirmClear = () => {
    clearNotifications();
    setClearConfirmOpen(false);
  };

  return (
    <>
      <PageHeader eyebrow="YOUR UPDATES" title="Notifications" description="Helpful reminders and activity from this local demo session." action={notifications.length > 0 ? <div className="notification-actions"><Button variant="secondary" size="sm" onClick={markAllNotificationsRead} disabled={unreadCount === 0} icon={<CheckCheck size={16} />}>Mark all read</Button><button type="button" className="icon-button subtle-danger" onClick={() => setClearConfirmOpen(true)} aria-label="Clear all notifications"><Trash2 size={17} /></button></div> : undefined} />

      {notifications.length === 0 ? <section className="card notifications-empty-card"><EmptyState title="You’re all caught up" description="There are no demo notifications right now. New simulated activity can add an update here." icon={Bell} action={<Button variant="secondary" onClick={() => navigate('/')}>Back to dashboard</Button>} /></section> : (
        <section className="card notifications-card" aria-label="Notifications list">
          <div className="notifications-list-heading"><div><h2>Recent updates</h2><p>{unreadCount ? `${unreadCount} unread ${unreadCount === 1 ? 'update' : 'updates'}` : 'Everything has been read'}</p></div><span className="notification-count-pill">{notifications.length}</span></div>
          <div className="notifications-list">
            {notifications.map((notification) => {
              const Icon = iconForKind(notification.kind);
              return <article className={`notification-row ${notification.read ? 'notification-read' : 'notification-unread'}`} key={notification.id}>
                <span className={`notification-kind-icon notification-kind-${notification.kind}`}><Icon size={18} /></span>
                <div className="notification-copy"><div className="notification-title-line"><h3>{notification.title}</h3>{!notification.read && <span className="unread-indicator">New</span>}</div><p>{notification.body}</p><span className="notification-time">{formatRelativeDate(notification.createdAt)}</span></div>
                <button type="button" className="notification-open-button" onClick={() => openNotification(notification.id, notification.href)} aria-label={`Open notification: ${notification.title}`}><ArrowRight size={17} /></button>
              </article>;
            })}
          </div>
          <div className="notifications-footnote"><LockKeyhole size={15} /><span>These messages are generated by the demo. No payment provider or bank sends them.</span></div>
        </section>
      )}

      <div className="notifications-help-link"><span><CircleHelp size={17} /></span><div><strong>Something doesn’t look right?</strong><small>Contact our sample support team.</small></div><Button variant="ghost" size="sm" onClick={() => navigate('/help')} icon={<ArrowRight size={15} />}>Get help</Button></div>

      <Modal open={clearConfirmOpen} title="Clear notifications?" subtitle="This removes demo alerts from the current session only." onClose={() => setClearConfirmOpen(false)} size="sm" footer={<><Button variant="secondary" onClick={() => setClearConfirmOpen(false)}>Keep them</Button><Button variant="danger" onClick={confirmClear} icon={<Trash2 size={16} />}>Clear all</Button></>}>
        <p className="modal-body-copy">You can continue using the demo after clearing these messages. New simulated activity may create new notifications.</p>
      </Modal>
    </>
  );
}
